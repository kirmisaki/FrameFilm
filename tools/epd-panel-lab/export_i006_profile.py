"""Regenerate I006 bindings from the checked-in provisional profile."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFILE = Path(__file__).resolve().parent / 'profiles/ark_512_i006.json'


def main():
    data = json.loads(PROFILE.read_text(encoding='utf-8'))
    assert data['id'] == 'i006-preview' and data['schema'] == 1
    assert len(data['recipeLinear']) == 512
    assert len(data['outputCodes']) == len(data['outputLinear']) == 423
    assert len(set(data['outputCodes'])) == 423
    assert all(0 <= code <= 511 for code in data['outputCodes'])
    names = {
        'abc512Floor': 'floor', 'abc512Center': 'center', 'abc512HullPlanes': 'hullPlanes',
        'abc512RecipeMeans': 'recipeLinear', 'abc512OutputCodes': 'outputCodes',
        'abc512OutputColors': 'outputLinear', 'abc512BaseCodes': 'baseCodes',
        'abc512BaseColors': 'baseLinear', 'abc512ShadowCodes': 'shadowCodes',
    }
    lines = ['// Generated by tools/epd-panel-lab/export_i006_profile.py. Do not edit.',
             '// Experimental camera-relative I006 profile; 512 optical colors are not certified.']
    for name, key in names.items():
        value = data[key]
        typename = 'double' if isinstance(value, float) else ('List<int>' if key.endswith('Codes') else ('List<double>' if key == 'center' else 'List<List<double>>'))
        lines.append('const ' + typename + ' ' + name + ' = ' + json.dumps(value, separators=(',', ':')) + ';')
    aliases = ','.join(str(int(key))+':'+str(value) for key,value in data.get('codeAliases', {}).items())
    lines.append('const Map<int,int> abc512CodeAliases = {'+aliases+'};')
    (ROOT / 'app/flutter_app/lib/frame_abc512_data.dart').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    script = '// Generated by tools/epd-panel-lab/export_i006_profile.py. Do not edit.\n'
    script += '(function(root){root.Ark512Profile=' + json.dumps(data, separators=(',', ':')) + ';})(typeof globalThis!=="undefined"?globalThis:window);\n'
    (ROOT / 'tools/ForFilm/js/ark-512-profile.js').write_text(script, encoding='utf-8')
    print('I006 Dart and JavaScript bindings generated from', PROFILE)


if __name__ == '__main__':
    main()
