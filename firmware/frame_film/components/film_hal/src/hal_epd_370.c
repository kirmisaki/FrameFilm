void hal_epd_display_pic(const unsigned char *picData)
{
    unsigned int i, j;
    unsigned char line[EPD_INPUT_LINE];

    if (picData == NULL)
    {
        sys_loge(EPD_TAG, "picData is NULL");
        return;
    }

    // 输入为每像素 1 字节的颜色表值（0x00/0xFF/0xFC/0xE0/0x03/0x1C），转换为 JD7601 面板字节
    EPD_W21_WriteCMD(DTM1);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (i = 0; i < EPD_HEIGHT; i++)
    {
        for (j = 0; j < EPD_INPUT_LINE; j++)
        {
            line[j] = (color_lut[picData[i * EPD_WIDTH + 2 * j]] << 4)
                      | color_lut[picData[i * EPD_WIDTH + 2 * j + 1]];
        }
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }

    epd_display_refresh_seq();
    sys_logi(EPD_TAG, "Display pic completed");
}

void hal_epd_display_film(const unsigned char *filmData)
{
    FilmHeader header;
    const unsigned char *pixelData;
    unsigned int i, j;
    unsigned char byte;
    unsigned char cc1, cc2;
    unsigned char line[EPD_INPUT_LINE];

    if (filmData == NULL)
    {
        sys_loge(EPD_TAG, "filmData is NULL");
        return;
    }

    if (film_parse_header(filmData, &header) != ESP_OK)
    {
        sys_loge(EPD_TAG, "Failed to parse film header");
        return;
    }

    sys_logi(EPD_TAG, "Film: %ux%u, format=0x%02X, %u frame(s), %lu bytes",
             header.screenWidth, header.screenHeight,
             header.format,
             (header.frameCount == 0) ? 1u : (unsigned)header.frameCount,
             (unsigned long)header.fileSize);

    pixelData = filmData + FILM_HEADER_SIZE;

    // 只做单帧显示：多帧文件取首帧。后续如需动画，再按 frameCount 循环展示。

    // 按 Format 判别 v1/v2 编码方式并分派到对应驱动路径
    switch (header.format)
    {
    case 0x01:  // v2 MonoFast：1bpp 位图，走黑白快刷
        sys_logi(EPD_TAG, "Film v2 MonoFast");
        hal_epd_display_mono(pixelData);
        return;

    case 0x02:  // v2 ColorQual：8bpp 索引，3 相刷新
        sys_logi(EPD_TAG, "Film v2 ColorQual");
        hal_epd_display_8bpp_mode(pixelData, 1);
        return;

    case 0x03:  // v2 ColorFast：8bpp 索引，2 相刷新
        sys_logi(EPD_TAG, "Film v2 ColorFast");
        hal_epd_display_8bpp_mode(pixelData, 0);
        return;

    default:    // 0x00 v1 4bpp：落入下方原有颜色转换路径
        break;
    }

    // 颜色转换：colorTable 索引 -> colorTable 实际值 -> JD7601 面板字节（4bpp 直写）
    EPD_W21_WriteCMD(DTM1);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (i = 0; i < EPD_HEIGHT; i++)
    {
        for (j = 0; j < EPD_INPUT_LINE; j++)
        {
            byte = pixelData[i * EPD_INPUT_LINE + j];
            cc1 = (byte >> 4) & 0x0F;
            cc2 = byte & 0x0F;
            line[j] = (color_lut[header.colorTable[cc1]] << 4)
                      | color_lut[header.colorTable[cc2]];
        }
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }

    epd_display_refresh_seq();
    sys_logi(EPD_TAG, "Film display completed");
}

void hal_epd_sleep(void)
{
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    EPD_W21_WriteCMD(DSLP);  // 0x07
    EPD_W21_WriteDATA(0xA5);

    m_mono_inited = false;   // 睡眠后需重新初始化 spectra

    sys_logi(EPD_TAG, "EPD sleep");
}

void hal_epd_pwroff(void)
{
    hal_epd_sleep();
    vTaskDelay(100 / portTICK_PERIOD_MS);

    sys_logi(EPD_TAG, "EPD power off");
}

void hal_epd_deinit(void)
{
    if (m_spi_device != NULL)
    {
        spi_bus_remove_device(m_spi_device);
        m_spi_device = NULL;
    }
    spi_bus_free(EPD_SPI_HOST);

    gpio_config_t io_conf =
    {
        .pin_bit_mask = (1ULL << EPD_BUSY_PIN) | (1ULL << EPD_RST_PIN) |
        (1ULL << EPD_DC_PIN)   | (1ULL << EPD_CS_PIN) |
        (1ULL << EPD_SCK_PIN)  | (1ULL << EPD_SDIN_PIN),
        .mode = GPIO_MODE_INPUT,
        .pull_up_en = GPIO_PULLUP_DISABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type = GPIO_INTR_DISABLE,
    };
    gpio_config(&io_conf);

    m_mono_inited = false;   // 释放后需重新初始化 spectra

    sys_logi(EPD_TAG, "EPD deinit, SPI and GPIOs released");
}

/*********************************************************************
 * 黑白快刷（MonoFast/MonoClear）
 *
 * 原理：输入 1bpp 位图（720x480/8 = 43200 字节），对每个像素编码
 * (上一帧, 当前帧) 的 2bit 跳变，配合 mono_fast/mono_clear 波形只驱动
 * 发生变化的像素，实现快速、无闪烁的"局刷"效果（JD7601 无窗口命令，
 * 这里仍是全屏写，但差分后仅变化像素被真正驱动）。
 *
 * 位图约定 1=黑、0=白（见 hal_epd.h / film.md 10.3）；面板码位极性见 MONO_CODE_BIT_WHITE。
 *********************************************************************/

static uint8_t epd_spectra_reverse_bits(uint8_t x)
{
    x = (uint8_t)((x >> 4) | (x << 4));
    x = (uint8_t)(((x >> 2) & 0x33) | ((x << 2) & 0xCC));
    return (uint8_t)(((x >> 1) & 0x55) | ((x << 1) & 0xAA));
}

/**
 * 位图字节 → mono 码位字节：先做字节内位序对齐（位图 MSB 在前 → 面板位序），
 * 再按码位极性取反（MONO_CODE_BIT_WHITE）。
 */
static uint8_t epd_spectra_mono_code_byte(uint8_t bitmap_byte)
{
    uint8_t v = epd_spectra_reverse_bits(bitmap_byte);

    if (MONO_CODE_BIT_WHITE)
    {
        v = (uint8_t)~v;
    }

    return v;
}

// 状态转换（prepare）：跨模式时选择对应过渡波形
// 上一帧初值按各分支实际得到的画面复位：清屏为黑 → INIT_BYTE；写白帧 → mono_write 自身已更新
static void epd_spectra_prepare(void)
{
    if (m_spectra_state == 0)
    {
        // native/quality → 全清理（内部已把上一帧复位为黑）
        epd_spectra_full_clear();
    }
    else if (m_spectra_state == 2)
    {
        // mono → 黑白清理：写完面板为白，上一帧由 mono_write 更新为白
        epd_spectra_wave(mono_clear);
        epd_spectra_mono_write(NULL);
        epd_spectra_refresh(true, false);
    }
    else if (m_spectra_state == 3)
    {
        // fast-color → 恢复：未写 mono 帧，按“清屏为黑”复位上一帧
        epd_spectra_wave(restore_after_fast_color);
        epd_spectra_refresh(true, false);
        memset(m_mono_prev, MONO_CODE_INIT_BYTE, EPD_MONO_BYTES);
    }
    m_spectra_state = 1;
}

// 写一帧黑白差分数据。mono_bitmap 为 NULL 时表示全白（清屏）
static void epd_spectra_mono_write(const uint8_t *mono_bitmap)
{
    uint8_t line[EPD_INPUT_LINE];

    EPD_W21_WriteCMD(DTM1);   // 0x10
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (int row = 0; row < EPD_HEIGHT; row++)
    {
        const uint8_t *src = mono_bitmap ? (mono_bitmap + row * EPD_MONO_LINE) : NULL;
        uint8_t *prev = m_mono_prev + row * EPD_MONO_LINE;
        for (int x = 0; x < EPD_MONO_LINE; x++)
        {
            uint8_t old = prev[x];
            uint8_t next = epd_spectra_mono_code_byte(src ? src[x] : 0x00);
            prev[x] = next;   // 更新上一帧（码位域）
            for (int j = 0; j < 4; j++)
            {
                line[x * 4 + j] = (uint8_t)(((old << 5) & 0x20) | ((next << 4) & 0x10)
                                            | (old & 2) | ((next >> 1) & 1));
                old >>= 2;
                next >>= 2;
            }
        }
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }
}

static void epd_spectra_mono_display(const uint8_t *mono_bitmap, bool is_clear)
{
    // mono 路径仅在 state != 1 && state != 2 时做状态转换
    if (m_spectra_state != 1 && m_spectra_state != 2)
    {
        epd_spectra_prepare();
    }

    epd_spectra_wave(is_clear ? mono_clear : mono_fast);
    epd_spectra_mono_write(mono_bitmap);
    epd_spectra_refresh(true, true);

    m_spectra_state = 2;
}

