// JD7601 命令（参考 GDEH037E01 官方驱动）
#define SOFT_START                    0xE9  // 软启动（初始化）
#define POF                           0x02  // Power off
#define PON                           0x04  // Power on
#define DSLP                          0x07  // Deep sleep
#define DTM1                          0x10  // 数据传输 1（写入帧数据）
#define REF                           0x12  // Display refresh

// ---- 48 色 spectra 波形命令 ----
#define JD7601_CMD_WAVE_PRE          0x00  // 波形载入前导（后跟 0x0F 0xA9）
#define JD7601_CMD_WRITE_LUT         0x20  // 写波形表（799 字节）
#define JD7601_CMD_PLL               0x30  // PLL 控制
#define JD7601_CMD_UNK_41            0x41  // 初始化命令（语义待确认）
#define JD7601_CMD_TEMP              0xE0  // 温度控制
#define JD7601_CMD_UNK_E6            0xE6  // 初始化命令（语义待确认）

#define EPD_INPUT_LINE                (EPD_WIDTH / 2)  // 每行字节数（4bpp，720/2=360）
#define EPD_MONO_LINE                 (EPD_WIDTH / 8)  // 每行字节数（1bpp，720/8=90）
#define EPD_MONO_BYTES                (EPD_WIDTH * EPD_HEIGHT / 8)  // 43200

/* mono 2bit 跳变码（code = 2*old + new）的码位语义。
 * .film 与时钟位图约定 1=黑、0=白，而实测面板的 mono_fast/mono_clear 波形把码位
 * 1 当白、0 当黑，故编码前统一取反；若换屏/换波形后画面反色，改这里即可。
 * 注意：这里只影响“新帧”的码位，上一帧初值见 MONO_CODE_INIT_BYTE。 */
#define MONO_CODE_BIT_WHITE           (1)

/* 面板经 full_clear / mono 清屏后的实际光学状态是“黑”（实测），差分刷新的上一帧
 * 初值以此为准，不能按“清屏=白”假设，否则首帧会整屏不动或整屏压黑。 */
#define MONO_CODE_INIT_BYTE           ((MONO_CODE_BIT_WHITE) ? 0x00 : 0xFF)

// BUSY 等待超时（ms）
#define BUSY_TIMEOUT_INIT_MS          (15000)
#define BUSY_TIMEOUT_POWER_MS         (60000)
#define BUSY_TIMEOUT_REFRESH_MS       (120000)
#define BUSY_TIMEOUT_POLARITY_MS      (3000)

#define FILM_HEADER_SIZE              (32)
#define FILM_COLOR_TABLE_SIZE         (16)
#define FILM_OFFSET_FILESIZE          (0x00)
#define FILM_OFFSET_SCREENWIDTH       (0x04)
#define FILM_OFFSET_SCREENHEIGHT      (0x06)
#define FILM_OFFSET_COLORCOUNT        (0x08)
#define FILM_OFFSET_FORMAT            (0x09)   // Format 判别码：0x00=v1 4bpp, 0x01=MonoFast, 0x02=ColorQual, 0x03=ColorFast
#define FILM_OFFSET_FRAMECOUNT        (0x0A)   // 帧数（小端），0/1 表示单帧
#define FILM_OFFSET_RESERVED          (0x0C)   // 保留字段（4 字节）
#define FILM_OFFSET_COLORTABLE        (0x10)

/*********************************************************************
* TYPEDEFS
*/
// .film 文件头（32 字节，与 docs/film/film.md 字段一一对应）
typedef struct
{
    uint32_t fileSize;      // 0x00 主体大小
    uint16_t screenWidth;   // 0x04 屏幕宽度（元数据）
    uint16_t screenHeight;  // 0x06 屏幕高度（元数据）
    uint8_t  colorCount;    // 0x08 颜色数量（仅 v1 使用）
    uint8_t  format;        // 0x09 格式判别码
    uint16_t frameCount;    // 0x0A 帧数（小端），0/1=单帧，>1=多帧动画
    uint8_t  reserved[4];   // 0x0C 保留字段
    uint8_t  colorTable[FILM_COLOR_TABLE_SIZE];   // 0x10 颜色表（仅 v1 使用）
} __attribute__((packed)) FilmHeader;

