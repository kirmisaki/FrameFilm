static bool epd_wait_busy(uint32_t timeout_ms)
{
    if (m_ignore_busy)
    {
        return true;
    }

    TickType_t start = xTaskGetTickCount();
    int busy_level = m_busy_active_low ? 0 : 1;

    while (gpio_get_level(EPD_BUSY_PIN) == busy_level)
    {
        vTaskDelay(pdMS_TO_TICKS(1));
        if (((xTaskGetTickCount() - start) * portTICK_PERIOD_MS) > timeout_ms)
        {
            sys_logw(EPD_TAG, "wait busy timeout (active_low=%d)", m_busy_active_low ? 1 : 0);
            EPD_PROFILE_TIMEOUT();
            return false;
        }
    }
    return true;
}

static void epd_try_fix_busy_polarity(void)
{
    if (epd_wait_busy(BUSY_TIMEOUT_POLARITY_MS))
    {
        sys_logi(EPD_TAG, "BUSY polarity ok (active_low=%d)", m_busy_active_low ? 1 : 0);
        return;
    }

    m_busy_active_low = !m_busy_active_low;
    if (epd_wait_busy(BUSY_TIMEOUT_POLARITY_MS))
    {
        sys_logi(EPD_TAG, "BUSY polarity switched (active_low=%d)", m_busy_active_low ? 1 : 0);
    }
    else
    {
        sys_logw(EPD_TAG, "BUSY polarity detection failed, ignore BUSY and continue");
        m_ignore_busy = true;
    }
}

static void reset(void)
{
    EPD_W21_RST_0;
    vTaskDelay(20 / portTICK_PERIOD_MS);
    EPD_W21_RST_1;
    vTaskDelay(20 / portTICK_PERIOD_MS);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    vTaskDelay(10 / portTICK_PERIOD_MS);

    /* 硬复位会清掉控制器内的帧数据，mono 差分刷新必须以复位后的状态重新建立会话，
       否则会拿失效的上一帧做差分（整屏闪/花屏）。 */
    m_mono_inited = false;
    m_panel_powered = false;   // 复位后面板回到未上电态
}

/*********************************************************************
 * NAME:        film_parse_header
 * DESCRIPTION: 解析并校验 .film 文件头。按 Format 得出单帧主体大小，
 *              再按 FrameCount（0/1 视为单帧）校验总主体大小。
 *********************************************************************/
static esp_err_t film_parse_header(const unsigned char *filmData, FilmHeader *header)
{
    if (filmData == NULL || header == NULL)
    {
        return ESP_ERR_INVALID_ARG;
    }

    memcpy(&header->fileSize,     &filmData[FILM_OFFSET_FILESIZE],      sizeof(uint32_t));
    memcpy(&header->screenWidth,  &filmData[FILM_OFFSET_SCREENWIDTH],   sizeof(uint16_t));
    memcpy(&header->screenHeight, &filmData[FILM_OFFSET_SCREENHEIGHT],  sizeof(uint16_t));
    memcpy(&header->colorCount,   &filmData[FILM_OFFSET_COLORCOUNT],    sizeof(uint8_t));
    memcpy(&header->format,       &filmData[FILM_OFFSET_FORMAT],        sizeof(uint8_t));
    memcpy(&header->frameCount,   &filmData[FILM_OFFSET_FRAMECOUNT],    sizeof(uint16_t));
    memcpy(header->reserved,      &filmData[FILM_OFFSET_RESERVED],      sizeof(header->reserved));
    memcpy(header->colorTable,    &filmData[FILM_OFFSET_COLORTABLE],    FILM_COLOR_TABLE_SIZE);

    // 按 Format（偏移 0x09）判别 v1/v2 编码方式，得出单帧主体大小
    uint32_t frameSize;
    switch (header->format)
    {
    case 0x00:  // v1：4bpp 颜色编码，ColorCount 取值 2-6
        if (header->colorCount < 2 || header->colorCount > 6)
        {
            sys_loge(EPD_TAG, "Invalid color count: %d (expected 2-6)", header->colorCount);
            return ESP_ERR_INVALID_SIZE;
        }
        frameSize = (EPD_WIDTH * EPD_HEIGHT) / 2;
        break;

    case 0x01:  // v2 MonoFast：1bpp 位图
        frameSize = (EPD_WIDTH * EPD_HEIGHT) / 8;
        break;

    case 0x02:  // v2 ColorQual：8bpp 索引
    case 0x03:  // v2 ColorFast：8bpp 索引
        frameSize = EPD_WIDTH * EPD_HEIGHT;
        break;

    default:
        sys_loge(EPD_TAG, "Unknown film format: 0x%02X", header->format);
        return ESP_ERR_INVALID_VERSION;
    }

    // FrameCount：0/1 视为单帧；>1 为多帧动画，主体按帧连续拼接
    uint32_t frameCount = (header->frameCount == 0) ? 1u : header->frameCount;
    uint32_t expectedSize = frameSize * frameCount;

    if (header->fileSize != expectedSize)
    {
        sys_loge(EPD_TAG, "File size mismatch: %lu (expected %lu, %u frame(s))",
                 (unsigned long)header->fileSize, (unsigned long)expectedSize,
                 (unsigned)frameCount);
        return ESP_ERR_INVALID_SIZE;
    }

    return ESP_OK;
}

// 写完整帧数据（4bpp，DTM1）
static void epd_display_refresh_seq(void)
{
    EPD_W21_WriteCMD(PON);   // 0x04 Power ON
    epd_wait_busy(BUSY_TIMEOUT_POWER_MS);
    vTaskDelay(10 / portTICK_PERIOD_MS);
    m_panel_powered = true;

    EPD_W21_WriteCMD(REF);   // 0x12 Display Refresh
    EPD_W21_WriteDATA(0x00);
    vTaskDelay(10 / portTICK_PERIOD_MS);
    epd_wait_busy(BUSY_TIMEOUT_REFRESH_MS);

    EPD_W21_WriteCMD(POF);   // 0x02 Power OFF
    EPD_W21_WriteDATA(0x00);
    epd_wait_busy(BUSY_TIMEOUT_POWER_MS);
    vTaskDelay(20 / portTICK_PERIOD_MS);
    m_panel_powered = false;
}

static void epd_display_solid(unsigned char color_byte)
{
    unsigned char line[EPD_INPUT_LINE];
    memset(line, color_byte, EPD_INPUT_LINE);

    EPD_W21_WriteCMD(DTM1);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (int row = 0; row < EPD_HEIGHT; row++)
    {
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }

    epd_display_refresh_seq();
}

/*********************************************************************
 * 48 色 SPECTRA 驱动（JD7601/GDEH037E01）
 *
 * 原理：每像素为 8bpp 索引（0-63），拆成两个 3bit 平面
 *   high = index >> 3, low = index & 7
 * 每个平面以 4bpp（2 像素/字节）写入控制器，配合不同波形表多次刷新，
 * 用时间抖动在 6 种物理颜色粒子间混出中间色。硬件本身仍是 6 色屏。
 *********************************************************************/

static void epd_spectra_wave(const uint8_t *lut)
{
    EPD_PROFILE_STAGE_BEGIN(LUT);
    // 波形载入前导 + 799 字节波形表（末尾对齐字节不进入 SPI）
    EPD_W21_WriteCMD(JD7601_CMD_WAVE_PRE);
    EPD_W21_WriteDATA(0x0F);
    EPD_W21_WriteDATA(0xA9);
    EPD_W21_WriteCMD(JD7601_CMD_WRITE_LUT);
    EPD_W21_WriteDATA_Bulk(lut, 799);
    EPD_PROFILE_STAGE_END(LUT);
}

static void epd_spectra_init(void)
{
    EPD_PROFILE_STAGE_BEGIN(INIT);
    EPD_PROFILE_PREPARE();
    // 复位序列（双脉冲），BUSY 极性沿用默认（低电平忙）
    EPD_W21_RST_0; vTaskDelay(20 / portTICK_PERIOD_MS);
    EPD_W21_RST_1; vTaskDelay(10 / portTICK_PERIOD_MS);
    EPD_W21_RST_0; vTaskDelay(20 / portTICK_PERIOD_MS);
    EPD_W21_RST_1; vTaskDelay(10 / portTICK_PERIOD_MS);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    vTaskDelay(10 / portTICK_PERIOD_MS);

    EPD_W21_WriteCMD(SOFT_START);   // 0xE9
    EPD_W21_WriteDATA(0x01);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);

    EPD_W21_WriteCMD(JD7601_CMD_PLL);     // 0x30
    EPD_W21_WriteDATA(0x04);
    EPD_W21_WriteCMD(JD7601_CMD_UNK_41);  // 0x41
    EPD_W21_WriteDATA(0x00);
    EPD_W21_WriteCMD(JD7601_CMD_TEMP);    // 0xE0
    EPD_W21_WriteDATA(0x02);
    EPD_W21_WriteCMD(JD7601_CMD_UNK_E6);  // 0xE6
    EPD_W21_WriteDATA(0x19);

    m_spectra_state = 0;
    m_panel_powered = false;   // 复位序列后面板回到未上电态
    EPD_PROFILE_STAGE_END(INIT);
}

// wait_cycle：先等 BUSY 拉低（进入忙），再等拉高（释放）
static void epd_spectra_wait_cycle(uint32_t assert_timeout_ms, uint32_t release_timeout_ms)
{
    TickType_t start;
    int busy_level = m_busy_active_low ? 0 : 1;

    // 等 BUSY 进入忙
    start = xTaskGetTickCount();
    while (gpio_get_level(EPD_BUSY_PIN) != busy_level)
    {
        vTaskDelay(pdMS_TO_TICKS(1));
        if (((xTaskGetTickCount() - start) * portTICK_PERIOD_MS) > assert_timeout_ms)
        {
            sys_logw(EPD_TAG, "spectra busy assert timeout");
            EPD_PROFILE_TIMEOUT();
            return;
        }
    }

    // 等 BUSY 释放
    start = xTaskGetTickCount();
    while (gpio_get_level(EPD_BUSY_PIN) == busy_level)
    {
        vTaskDelay(pdMS_TO_TICKS(1));
        if (((xTaskGetTickCount() - start) * portTICK_PERIOD_MS) > release_timeout_ms)
        {
            sys_logw(EPD_TAG, "spectra busy release timeout");
            EPD_PROFILE_TIMEOUT();
            return;
        }
    }
}

/**
 * @brief 面板断电（POF），幂等：本来就断电时什么都不做
 *
 * 从 epd_spectra_refresh 里拆出来，是因为黑白快刷会话会在播放期间保持上电、
 * 只在停止播放时补一次断电（见 hal_epd_mono_session_end）。
 */
static void epd_spectra_power_off(void)
{
    if (!m_panel_powered)
    {
        return;
    }

    EPD_PROFILE_STAGE_BEGIN(POF);
    EPD_W21_WriteCMD(POF);   // 0x02
    EPD_W21_WriteDATA(0x00);
    epd_spectra_wait_cycle(1000, BUSY_TIMEOUT_POWER_MS);
    vTaskDelay(20 / portTICK_PERIOD_MS);

    m_panel_powered = false;
    EPD_PROFILE_STAGE_END(POF);
}

static void epd_spectra_refresh(bool power_on, bool power_off)
{
    /* PON 幂等：会话内已上电就不再付一次 PON 的 BUSY 等待（实测约 100ms/次） */
    if (power_on && !m_panel_powered)
    {
        EPD_PROFILE_STAGE_BEGIN(PON);
        EPD_W21_WriteCMD(PON);   // 0x04
        epd_spectra_wait_cycle(1000, BUSY_TIMEOUT_POWER_MS);
        vTaskDelay(10 / portTICK_PERIOD_MS);
        m_panel_powered = true;
        EPD_PROFILE_STAGE_END(PON);
    }

    EPD_PROFILE_STAGE_BEGIN(REF);
    EPD_PROFILE_REF_COUNT();
    EPD_BUSY_TRACE(5);
    EPD_W21_WriteCMD(REF);   // 0x12
    EPD_W21_WriteDATA(0x00);
    EPD_BUSY_TRACE(6);
    epd_spectra_wait_cycle(1000, BUSY_TIMEOUT_REFRESH_MS);
    EPD_BUSY_TRACE(7);
    vTaskDelay(10 / portTICK_PERIOD_MS);
    EPD_BUSY_TRACE(8);

    EPD_PROFILE_STAGE_END(REF);

    if (power_off)
    {
        epd_spectra_power_off();
    }
}

// 写入一整帧（172800 字节 = 480 行 x 360 字节）的填充值
static void epd_spectra_fill(uint8_t fill_byte)
{
    EPD_PROFILE_STAGE_BEGIN(RAM);
    uint8_t line[EPD_INPUT_LINE];
    memset(line, fill_byte, EPD_INPUT_LINE);

    EPD_W21_WriteCMD(DTM1);   // 0x10
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (int row = 0; row < EPD_HEIGHT; row++)
    {
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }

    EPD_PROFILE_STAGE_END(RAM);
    epd_spectra_refresh(true, true);
}

static void epd_spectra_full_clear(void)
{
    EPD_PROFILE_PREPARE();
    epd_spectra_wave(full_clear);
    epd_spectra_fill(0x00);
    memset(m_mono_prev, MONO_CODE_INIT_BYTE, EPD_MONO_BYTES);   // 清屏后面板为黑，上一帧按黑复位
    m_spectra_state = 1;
}

// 把一行 8bpp 索引编码为一个 4bpp 平面的 360 字节
static void epd_spectra_encode_row(const uint8_t *row, uint8_t plane, uint8_t *out)
{
    for (int x = 0; x < EPD_WIDTH; x += 2)
    {
        uint8_t a = row[x];
        uint8_t b = row[x + 1];
        if (plane == 0) { a >>= 3; b >>= 3; }
        else            { a &= 7;  b &= 7;  }
        *out++ = (uint8_t)((a << 4) | b);
    }
}

// 写一个平面的整帧数据（输入为 8bpp 索引缓冲）
static void epd_spectra_write_plane(const uint8_t *index8, uint8_t plane)
{
    EPD_PROFILE_STAGE_BEGIN(RAM);
    uint8_t line[EPD_INPUT_LINE];

    EPD_W21_WriteCMD(DTM1);   // 0x10
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (int row = 0; row < EPD_HEIGHT; row++)
    {
        epd_spectra_encode_row(index8 + row * EPD_WIDTH, plane, line);
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }
    EPD_PROFILE_STAGE_END(RAM);
}

#ifdef CONFIG_ARK_EPD_ABC_DIAG
/* RAM-only writer: epd_spectra_fill() also refreshes and must NOT be used here. */
static void epd_spectra_write_constant(uint8_t code)
{
    EPD_PROFILE_STAGE_BEGIN(RAM);
    uint8_t line[EPD_INPUT_LINE];
    memset(line, (uint8_t)((code << 4) | code), sizeof(line));
    EPD_W21_WriteCMD(DTM1);
    epd_wait_busy(BUSY_TIMEOUT_INIT_MS);
    for (int row = 0; row < EPD_HEIGHT; row++)
    {
        EPD_W21_WriteDATA_Bulk(line, EPD_INPUT_LINE);
    }
    EPD_PROFILE_STAGE_END(RAM);
}
#endif

// 彩色多相位刷新：mode 0 = ColorFast(2 相), 1 = ColorQual(3 相)
static void epd_spectra_display_color(const uint8_t *index8, uint8_t mode)
{
    // 清理条件：ColorFast 在 state != 1 时清理；
    // ColorQual 仅在 mono(2)/fast-color(3) 之后（state >= 2）才清理
    bool need_clear = (mode == 0) ? (m_spectra_state != 1)
                                  : (m_spectra_state >= 2);
#ifdef CONFIG_ARK_EPD_ABC_DIAG
    /* Same starting operation for all diagnostic modes, including mode 0.
     * This adds one clear REF to the original three Qual REFs, for four total. */
    if (mode == 1) need_clear = true;
#endif
    if (need_clear)
    {
        epd_spectra_full_clear();
    }

    if (mode == 0)
    {
        // ColorFast：高平面 -> 刷新 -> 低平面 -> 刷新 -> 重写高平面（不刷新）
        epd_spectra_wave(fast_color_phase1);
        epd_spectra_write_plane(index8, 0);
        epd_spectra_refresh(true, false);

        epd_spectra_wave(fast_color_phase2);
        epd_spectra_write_plane(index8, 1);
        epd_spectra_refresh(false, true);

        epd_spectra_write_plane(index8, 0);
        m_spectra_state = 3;
    }
    else
    {
        // ColorQual：高平面 -> 刷新 -> 换波形复用 RAM -> 刷新 -> 低平面 -> 刷新
        epd_spectra_wave(qual_phase1);
        epd_spectra_write_plane(index8, 0);
        epd_spectra_refresh(true, false);

        epd_spectra_wave(qual_phase2);
#ifdef CONFIG_ARK_EPD_ABC_DIAG
        const uint8_t diag_mode = index8[0] >> 3;
        if (diag_mode == 1)
        {
            epd_spectra_write_plane(index8, 0);
        }
        else if (diag_mode == 2)
        {
            epd_spectra_write_constant(index8[0] & 7);
        }
        /* Mode 1 controls the extra 172800-byte transfer slot of mode 2.
         * Mode 0 retains RAM reuse; complete refresh timing is not identical. */
#endif
        epd_spectra_refresh(false, false);   // 复用同一控制器 RAM，不重传图

        epd_spectra_wave(qual_phase3);
        epd_spectra_write_plane(index8, 1);
        epd_spectra_refresh(false, true);
        m_spectra_state = 0;
    }
}

