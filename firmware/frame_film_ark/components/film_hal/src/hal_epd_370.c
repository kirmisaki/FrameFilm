// 带 mode 的 8bpp 显示：mode 0 = ColorFast(2 相), 1 = ColorQual(3 相)
void hal_epd_display_8bpp_mode(const unsigned char *index8Data, uint8_t mode)
{
    EPD_PROFILE_BEGIN(mode == 0 ? "color_fast" : "color_qual");
    if (index8Data == NULL)
    {
        sys_loge(EPD_TAG, "index8Data is NULL");
        EPD_PROFILE_ERROR(ESP_ERR_INVALID_ARG);
        EPD_PROFILE_END();
        return;
    }
    if (mode > 1)
    {
        sys_loge(EPD_TAG, "Invalid 8bpp mode: %u (expected 0=ColorFast, 1=ColorQual)", mode);
        EPD_PROFILE_ERROR(ESP_ERR_INVALID_ARG);
        EPD_PROFILE_END();
        return;
    }

#ifdef CONFIG_ARK_EPD_ABC_DIAG
    if (mode == 1)
    {
        const uint8_t diag_mode = index8Data[0] >> 3;
        if (diag_mode > 2)
        {
            sys_loge(EPD_TAG, "ABC diagnostic rejected native marker 0x%02X", index8Data[0]);
            EPD_PROFILE_ERROR(ESP_ERR_INVALID_ARG);
            EPD_PROFILE_END();
            return;
        }
        sys_logi(EPD_TAG, "ABC_DIAG mode=%u B=%u clear=1 qual_ref=3 extra_ram=%u",
                 diag_mode, index8Data[0] & 7, diag_mode == 0 ? 0u : 172800u);
    }
#endif
    epd_spectra_init();
    epd_spectra_display_color(index8Data, mode);
    EPD_PROFILE_END();
    sys_logi(EPD_TAG, "Display 8bpp mode=%u completed", mode);
}

void hal_epd_display_mono(const unsigned char *mono_bitmap)
{
    EPD_PROFILE_BEGIN("mono");
    if (mono_bitmap == NULL)
    {
        sys_loge(EPD_TAG, "mono_bitmap is NULL");
        EPD_PROFILE_ERROR(ESP_ERR_INVALID_ARG);
        EPD_PROFILE_END();
        return;
    }

    // 黑白快刷会话首次调用时初始化一次，之后跨调用保持上一帧实现差分局刷
    if (!m_mono_inited)
    {
        epd_spectra_init();
        m_mono_inited = true;
    }

    epd_spectra_mono_display(mono_bitmap, false);
    EPD_PROFILE_END();
    sys_logd(EPD_TAG, "Display mono (B/W fast refresh) completed");
}

uint32_t hal_epd_get_capabilities(void)
{
    return (uint32_t)(EPD_CAP_4BPP | EPD_CAP_8BPP | EPD_CAP_MONOFAST);
}
